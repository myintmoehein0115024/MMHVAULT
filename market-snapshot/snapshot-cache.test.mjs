import assert from 'node:assert/strict';
import {refreshMarketSnapshot,readMarketSnapshot} from './snapshot-cache.mjs';
import {SNAPSHOT_INTERVAL_MS} from './currency-snapshot.mjs';
const now=Date.parse('2026-01-02T12:00:00Z');
const state=new Map();let tail=Promise.resolve();
const store={transaction(fn){const p=tail.then(()=>fn({get:async k=>state.get(k),put:async(k,v)=>state.set(k,v)}));tail=p.catch(()=>{});return p}};
const payload=time=>({result:1,data:{as_of:new Date(time).toISOString(),currencies:[{series:{kind:'currency',code:'USD',unit:'unit',quote_type:'two_way',quote_currency:'MMK'},quote:{recorded_at:new Date(time).toISOString(),buy:'100',sell:'110',buy_change:'2',sell_change:'3'},stale:false}]}});
let calls=0;
const fetchMarket=async()=>{calls++;return payload(now)};
assert.equal(await readMarketSnapshot({store,now}),null);
const results=await Promise.all(Array.from({length:30},()=>refreshMarketSnapshot({store,fetchMarket,now})));
assert.equal(calls,1);
assert.equal(results.filter(x=>x.status==='updated').length,1);
assert.equal(results.filter(x=>x.status==='already-attempted').length,29);
const first=await readMarketSnapshot({store,now});
assert.equal(first.quotes.USD.buy,100);
assert.equal(first.stale,false);
assert.equal(calls,1);
const next=now+SNAPSHOT_INTERVAL_MS;
const fail=await refreshMarketSnapshot({store,now:next,fetchMarket:async()=>{calls++;throw new Error('private upstream failure')}});
assert.equal(fail.status,'upstream-unavailable');
assert.equal((await refreshMarketSnapshot({store,now:next,fetchMarket})).status,'already-attempted');
const stale=await readMarketSnapshot({store,now:next});
assert.equal(stale.stale,true);
assert.equal(stale.asOf,first.asOf);
assert.equal(calls,2);
const later=next+SNAPSHOT_INTERVAL_MS;
assert.equal((await refreshMarketSnapshot({store,now:later,fetchMarket:async()=>payload(now-1000)})).status,'older-snapshot');
assert.equal((await readMarketSnapshot({store,now:later})).asOf,first.asOf);
assert.equal((await refreshMarketSnapshot({store,now:later+SNAPSHOT_INTERVAL_MS,fetchMarket:async()=>({result:0})})).status,'invalid-snapshot');
assert.equal((await readMarketSnapshot({store,now:later+SNAPSHOT_INTERVAL_MS})).quotes.USD.sell,110);
const final=later+2*SNAPSHOT_INTERVAL_MS;
assert.equal((await refreshMarketSnapshot({store,now:final,fetchMarket:async()=>payload(final)})).status,'updated');
assert.equal((await readMarketSnapshot({store,now:final})).stale,false);
console.log('PASS: synthetic cache scheduling and stale fallback');
