import assert from 'node:assert/strict';
import {normalizeCurrencySnapshot,directCurrencyQuote,SNAPSHOT_INTERVAL_MS} from './currency-snapshot.mjs';
const now=Date.parse('2026-01-02T12:00:00Z');
const item={series:{kind:'currency',code:'usd',unit:'unit',quote_type:'two_way',quote_currency:'MMK'},quote:{recorded_at:'2026-01-02T11:00:00Z',buy:'100',sell:'110',buy_change:'-2',sell_change:null},stale:false};
const payload={result:1,data:{as_of:'2026-01-02T11:30:00Z',currencies:[item]}};
const snap=normalizeCurrencySnapshot(payload,now);
assert.equal(snap.quotes.USD.buy,100);
assert.equal(snap.quotes.USD.sellChange,null);
assert.equal(snap.quotes.USD.buyChange,-2);
assert.equal(directCurrencyQuote(snap,'MMK','USD',now).stale,false);
assert.equal(directCurrencyQuote(snap,'MMK','USD',now+SNAPSHOT_INTERVAL_MS).stale,true);
assert.equal(directCurrencyQuote(snap,'USD','THB',now),null);
assert.equal(directCurrencyQuote(snap,'MMK','XXX',now),null);
for(const bad of [null,'',0,'NaN','Infinity','0xFF',-1])assert.equal(normalizeCurrencySnapshot({...payload,data:{...payload.data,currencies:[{...item,quote:{...item.quote,buy:bad}}]}},now),null);
assert.equal(normalizeCurrencySnapshot({...payload,data:{...payload.data,currencies:[item,item]}},now),null);
assert.equal(normalizeCurrencySnapshot({...payload,data:{...payload.data,currencies:[{...item,series:{...item.series,quote_currency:'USD'}}]}},now),null);
assert.equal(normalizeCurrencySnapshot({...payload,data:{...payload.data,currencies:[{...item,quote:{...item.quote,recorded_at:'2026-01-03T00:00:00Z'}}]}},now),null);
assert.equal(normalizeCurrencySnapshot({...payload,result:0},now),null);
assert.equal(normalizeCurrencySnapshot({...payload,data:{...payload.data,currencies:[{...item,quote:{...item.quote,sell:'90'}}]}},now),null);
assert.equal(normalizeCurrencySnapshot({...payload,data:{...payload.data,currencies:[{...item,stale:true}]}},now).quotes.USD.stale,true);
console.log('PASS: currency snapshot validation and direct MMK display; synthetic data only');
