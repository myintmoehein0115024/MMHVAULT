BEGIN;

DO $staging_preflight$
BEGIN
  IF to_regclass('public.transactions') IS NOT NULL OR
     to_regclass('public.personal_configuration') IS NOT NULL THEN
    RAISE EXCEPTION
      'Refusing APP V11 sandbox creation: finance table already exists. Abort; investigate target project.';
  END IF;
END
$staging_preflight$;

-- The two minimal live-compatible tables are empty when created.
-- Keep the existing N10 authentication QA tables entirely untouched.
CREATE TABLE public.transactions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  tx_date date NOT NULL,
  type text NOT NULL,
  category text NOT NULL,
  from_account text,
  from_amount numeric DEFAULT 0,
  to_account text,
  to_amount numeric DEFAULT 0,
  note text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX mmh_v117_staging_transactions_owner_date_idx
  ON public.transactions(user_id, tx_date DESC);

CREATE TABLE public.personal_configuration (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  config jsonb NOT NULL DEFAULT '{}'::jsonb,
  language text NOT NULL DEFAULT 'en',
  timezone text NOT NULL DEFAULT 'UTC',
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.personal_configuration ENABLE ROW LEVEL SECURITY;

-- No anonymous finance access. An authenticated user may only access
-- the rows with their own auth.uid(). Do not trust user-editable metadata.
REVOKE ALL ON TABLE public.transactions, public.personal_configuration
  FROM anon, PUBLIC;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.transactions
  TO authenticated;
GRANT SELECT, INSERT, UPDATE ON TABLE public.personal_configuration
  TO authenticated;

CREATE POLICY mmh_v117_qa_tx_read
  ON public.transactions FOR SELECT TO authenticated
  USING (user_id = (SELECT auth.uid()));
CREATE POLICY mmh_v117_qa_tx_insert
  ON public.transactions FOR INSERT TO authenticated
  WITH CHECK (user_id = (SELECT auth.uid()));
CREATE POLICY mmh_v117_qa_tx_update
  ON public.transactions FOR UPDATE TO authenticated
  USING (user_id = (SELECT auth.uid()))
  WITH CHECK (user_id = (SELECT auth.uid()));
CREATE POLICY mmh_v117_qa_tx_delete
  ON public.transactions FOR DELETE TO authenticated
  USING (user_id = (SELECT auth.uid()));

CREATE POLICY mmh_v117_qa_config_read
  ON public.personal_configuration FOR SELECT TO authenticated
  USING (user_id = (SELECT auth.uid()));
CREATE POLICY mmh_v117_qa_config_insert
  ON public.personal_configuration FOR INSERT TO authenticated
  WITH CHECK (user_id = (SELECT auth.uid()));
CREATE POLICY mmh_v117_qa_config_update
  ON public.personal_configuration FOR UPDATE TO authenticated
  USING (user_id = (SELECT auth.uid()))
  WITH CHECK (user_id = (SELECT auth.uid()));

COMMIT;

